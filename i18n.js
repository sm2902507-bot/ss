  // ── State ─────────────────────────────────────────────────
  let current = localStorage.getItem(LANG_KEY) || 'en';

  // ── Helpers ───────────────────────────────────────────────
  function get(key, ...args) {
    const lang = t[current] || t.en;
    const val  = lang[key] !== undefined ? lang[key] : (t.en[key] || key);
    return typeof val === 'function' ? val(...args) : val;
  }

  function setLang(code) {
    if (!t[code]) return;
    current = code;
    localStorage.setItem(LANG_KEY, code);
    document.documentElement.lang = code;
    document.documentElement.dir  = languages[code]?.dir || 'ltr';
  }

  function getLangMeta(code) { return languages[code] || languages.en; }
  function getAllLangs()      { return Object.entries(languages).map(([code, meta]) => ({ code, ...meta })); }
  function currentCode()     { return current; }
  function voiceLang()       { return languages[current]?.voiceLang || 'en-US'; }

  // ── Apply translations to DOM ─────────────────────────────
  function applyToDOM() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      el.textContent = get(key);
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      el.placeholder = get(el.dataset.i18nPh);
    });
  }

  return { get, setLang, getLangMeta, getAllLangs, currentCode, voiceLang, applyToDOM };
